// Run before publishing changes to index.html, shared.js, or variant-f.js.
// Static iframe nodes start loading during HTML parsing and survive page initialization.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const context = vm.createContext({ window: {} });
for (const file of ['shared.js', 'variant-f.js']) {
  vm.runInContext(await readFile(new URL(file, import.meta.url), 'utf8'), context, { filename: file });
}
const markup = context.window.VariantF();
const html = (await readFile(new URL('index.html', import.meta.url), 'utf8'))
  .replace(/  <script data-daylight-redirect>[\s\S]*?<\/script>\n/, '')
  .replace('<!-- A–E remain design previews. F uses the live GHL quote form and thank-you.html. -->',
    '<!-- Generated by node build-daylight.mjs. Edit variant-f.js, shared.js, and index.html instead. -->')
  .replace('<title>Super Shine Auto Detailing | Ceramic Coating Prototypes</title>',
    '<title>Daylight Studio | Super Shine Auto Detailing</title>')
  .replace('<body>', '<body class="variant-f">')
  .replace('<div id="app"></div>', `<div id="app" data-variant="F">${markup}</div>`)
  .replace('  <script src="shared.js',
    '  <script id="ghl-form-embed" src="https://link.msgsndr.com/js/form_embed.js" async></script>\n  <script src="shared.js')
  .replace(/<noscript>[\s\S]*?<\/noscript>/,
    '<noscript>To request a quote, enable JavaScript or call <a href="tel:+17752207064">(775) 220-7064</a>.</noscript>');
await writeFile(new URL('daylight.html', import.meta.url), html);
console.log('Built daylight.html with parser-loaded GHL forms.');
